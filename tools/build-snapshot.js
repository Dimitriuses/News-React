/*
 * Builds src/newsSnapshot.js and public/news/*.svg from the twelve articles that were
 * hardcoded into App.js's initial state in 2019.
 *
 * Two things happen here:
 *
 *  1. The articles are reshaped to the field names the components actually read. The 2019
 *     seed data used `image`/`id`, but once App.js switched to the live API the components
 *     were changed to read `urlToImage` and to key on `publishedAt` -- which is why the
 *     seed data stopped rendering and became dead code.
 *
 *  2. Every `image` URL is replaced with a locally generated SVG. The originals were
 *     hotlinks to news photographs on twelve publishers' CDNs: the repository has no right
 *     to redistribute them, and three of them no longer resolve anyway. See NOTICE.md.
 *
 * Run with: node tools/build-snapshot.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SVG_DIR = path.join(ROOT, 'public', 'news');

// The 2019 seed articles, read out of the preserved original rather than retyped.
const original = fs.readFileSync(path.join(__dirname, 'seed-2019.json'), 'utf8');
const articles = JSON.parse(original);

/** "Headline blah - CNN" -> "CNN" */
function publisherOf(title) {
  const m = /\s-\s([^-]+)$/.exec(title);
  return m ? m[1].trim() : 'News';
}

/** Deterministic hue per publisher, so the palette is stable across rebuilds. */
function hueOf(name) {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) % 360;
  return h;
}

function slugOf(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

/**
 * A 16:9 placeholder card: two-tone diagonal ground, a stack of "text" rules suggesting a
 * column of newsprint, and the publisher's name. No external fonts, no raster data.
 */
function svgFor(publisher, index) {
  const hue = hueOf(publisher);
  const bg = `hsl(${hue}, 42%, 26%)`;
  const bg2 = `hsl(${(hue + 28) % 360}, 46%, 17%)`;
  const ink = `hsl(${hue}, 34%, 76%)`;
  const rules = [];
  for (let i = 0; i < 5; i++) {
    const w = 120 + ((index * 37 + i * 53) % 150);
    rules.push(
      `<rect x="48" y="${150 + i * 26}" width="${w}" height="9" rx="4.5" fill="${ink}" opacity="${0.5 - i * 0.07}"/>`
    );
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360" viewBox="0 0 640 360" role="img" aria-label="${publisher}">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${bg}"/>
      <stop offset="1" stop-color="${bg2}"/>
    </linearGradient>
  </defs>
  <rect width="640" height="360" fill="url(#g)"/>
  <rect x="48" y="60" width="300" height="18" rx="9" fill="${ink}" opacity="0.85"/>
  <rect x="48" y="92" width="196" height="18" rx="9" fill="${ink}" opacity="0.65"/>
${rules.join('\n')}
  <circle cx="512" cy="248" r="64" fill="${ink}" opacity="0.13"/>
  <text x="48" y="316" font-family="Segoe UI, Helvetica, Arial, sans-serif" font-size="26"
        font-weight="600" fill="${ink}" opacity="0.95">${publisher}</text>
</svg>
`;
}

fs.mkdirSync(SVG_DIR, { recursive: true });
for (const f of fs.readdirSync(SVG_DIR)) {
  if (f.endsWith('.svg')) fs.unlinkSync(path.join(SVG_DIR, f));
}

const seen = new Map();
const out = articles.map((a, i) => {
  const publisher = publisherOf(a.title);
  const slug = slugOf(publisher);
  if (!seen.has(slug)) {
    fs.writeFileSync(path.join(SVG_DIR, slug + '.svg'), svgFor(publisher, i), 'utf8');
    seen.set(slug, true);
  }
  return {
    source: { name: publisher },
    title: a.title,
    description: a.description,
    url: a.url,
    urlToImage: 'news/' + slug + '.svg',
  };
});

const banner = `// Twelve headlines from 26 September 2019, captured by hand into App.js's initial state
// while the app was being built and left unread once it switched to the live API.
//
// They are the app's data source now: the newsapi.org key that used to sit in APIClient.js
// was public for seven years and has been removed, so the published demo ships this instead
// of a credential. Generated by tools/build-snapshot.js -- edit that, not this file.
//
// The images are locally generated placeholders. The 2019 originals were hotlinks to the
// publishers' own photographs; see NOTICE.md.

const newsSnapshot = ${JSON.stringify(out, null, 2)};

export default newsSnapshot;
`;

fs.writeFileSync(path.join(ROOT, 'src', 'newsSnapshot.js'), banner, 'utf8');
console.log('wrote src/newsSnapshot.js  (' + out.length + ' articles)');
console.log('wrote ' + seen.size + ' placeholder SVGs to public/news/');
